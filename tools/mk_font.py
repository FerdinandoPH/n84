#!/usr/bin/env python3
"""Extract printable ASCII glyphs from a PSF console font into a C header.

N84 uses the X11 "misc-fixed" 8x13 font (public domain), as shipped by
console-setup in /usr/share/consolefonts/Lat15-Fixed13.psf.gz.

    tools/mk_font.py /usr/share/consolefonts/Lat15-Fixed13.psf.gz > src/frontend/font8x13.h
"""
import gzip, struct, sys

def load_psf(path):
    data = gzip.open(path).read() if path.endswith('.gz') else open(path, 'rb').read()
    if data[:2] == b'\x36\x04':                       # PSF1
        mode, h = data[2], data[3]
        n = 512 if mode & 1 else 256
        w, size, off = 8, h, 4
        glyphs = [data[off + i * size: off + (i + 1) * size] for i in range(n)]
        table = data[off + n * size:]
        umap = {}
        if mode & 2:                                  # unicode table, u16 entries
            g, i = 0, 0
            while g < n and i + 1 < len(table):
                u = struct.unpack_from('<H', table, i)[0]; i += 2
                if u == 0xFFFF: g += 1
                elif u != 0xFFFE: umap.setdefault(u, g)
        return w, h, glyphs, umap
    magic, ver, hsz, flags, n, size, h, w = struct.unpack_from('<IIIIIIII', data)
    assert magic == 0x864ab572
    glyphs = [data[hsz + i * size: hsz + (i + 1) * size] for i in range(n)]
    umap = {}
    if flags & 1:                                     # UTF-8 unicode table
        table = data[hsz + n * size:]
        g, i = 0, 0
        while g < n and i < len(table):
            b = table[i]
            if b == 0xFF: g += 1; i += 1; continue
            if b == 0xFE: i += 1; continue
            l = 1 if b < 0x80 else 2 if b < 0xE0 else 3 if b < 0xF0 else 4
            umap.setdefault(table[i:i + l].decode('utf-8', 'replace'), g)
            i += l
        umap = {ord(k): v for k, v in umap.items() if len(k) == 1}
    return w, h, glyphs, umap

w, h, glyphs, umap = load_psf(sys.argv[1])
assert w == 8
print('/* Generated by tools/mk_font.py from %s.' % sys.argv[1].split('/')[-1])
print(' * X11 "misc-fixed" %dx%d font: public domain. Glyphs for ASCII 32..126. */' % (w, h))
print('#ifndef N84_FONT_H\n#define N84_FONT_H\n#include <stdint.h>')
print('#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST 32\n#define FONT_LAST 126' % (w, h))
print('static const uint8_t font_data[FONT_LAST - FONT_FIRST + 1][FONT_H] = {')
for c in range(32, 127):
    g = glyphs[umap.get(c, c)]
    print('    { %s }, /* %r */' % (', '.join('0x%02X' % b for b in g[:h]), chr(c)))
print('};\n#endif')
